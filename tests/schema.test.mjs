import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const owner = '00000000-0000-0000-0000-000000000001', outsider = '00000000-0000-0000-0000-000000000002';
const must = 'df9db72b-b8ee-4178-bc1d-e5f55c9dcca7', other = '32dd9a59-8fa4-45f3-a20f-e801549179d1';
test('prepared SQL enforces capacity, identity, archive and owner-only CRUD in isolated Postgres', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); insert into auth.users values ('${owner}'),('${outsider}');
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth,public to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;
      create table public.lists(id uuid primary key, title text not null);
      create table public.tasks(id uuid primary key default gen_random_uuid(),list_id uuid references lists(id),content text not null,due_date text,urgency integer,is_done boolean default false,created_at timestamptz default now());
      insert into lists values ('${must}','Must Do Today'),('${other}','Other');`);
    const capacity = await readFile(new URL('../supabase/migrations/20261030224513_todo_list_metadata_capacity.sql', import.meta.url), 'utf8');
    const access = await readFile(new URL('../supabase/migrations/20261030224943_todo_owner_access.sql', import.meta.url), 'utf8');
    await db.exec(capacity);
    await assert.rejects(db.exec(`update lists set is_archived=true where id='${must}'`), /Pinned lists/);
    await assert.rejects(db.exec(`update lists set id=gen_random_uuid() where id='${other}'`), /identity/);
    await assert.rejects(db.exec(access), /verified existing Auth/);
    await db.exec(`set todo.owner_id='${owner}'`); await db.exec(access);
    await db.exec(`set role anon`);
    await assert.rejects(db.query('select * from tasks'), /permission denied/);
    await assert.rejects(db.exec(`insert into lists values (gen_random_uuid(),'unauthorized',false,null)`), /permission denied/);
    await db.exec(`reset role; set role authenticated; set request.jwt.claim.sub='${outsider}'`);
    assert.equal((await db.query('select * from lists')).rows.length, 0);
    await assert.rejects(db.exec(`insert into tasks(list_id,content) values ('${other}','unauthorized')`), /row-level security|Destination list is unavailable/);
    await db.exec(`set request.jwt.claim.sub='${owner}'`);
    assert.equal((await db.query('select * from lists')).rows.length, 2);
    await db.exec(`insert into tasks(list_id,content) values ('${must}','one'),('${must}','two'),('${must}','three')`);
    await assert.rejects(db.exec(`insert into tasks(list_id,content) values ('${must}','four')`), /3 active tasks/);
    await db.exec(`update tasks set is_done=true where content='one'; insert into tasks(list_id,content) values ('${must}','four')`);
    await assert.rejects(db.exec(`update tasks set is_done=false where content='one'`), /3 active tasks/);
    await db.exec(`insert into tasks(list_id,content) values ('${other}','move')`);
    const before = (await db.query(`select * from tasks where content='move'`)).rows[0];
    await assert.rejects(db.exec(`update tasks set list_id='${must}' where id='${before.id}'`), /3 active tasks/);
    await db.exec(`update tasks set is_done=true where content='two'; update tasks set list_id='${must}' where id='${before.id}'`);
    const after = (await db.query(`select * from tasks where id='${before.id}'`)).rows[0];
    assert.equal(after.content, before.content); assert.equal(after.created_at.getTime(), before.created_at.getTime());
    await db.exec(`update lists set is_archived=true where id='${other}'`);
    await assert.rejects(db.exec(`insert into tasks(list_id,content) values ('${other}','blocked')`), /archived/);
    await db.exec(`update lists set is_archived=false where id='${other}'; update lists set title='Renamed',sort_order=2 where id='${other}'`);
    await db.exec(`set request.jwt.claim.sub='${outsider}'`);
    assert.equal((await db.query('select * from tasks')).rows.length, 0);
    assert.equal((await db.query(`update tasks set content='hacked' returning id`)).rows.length, 0);
    assert.equal((await db.query('delete from tasks returning id')).rows.length, 0);
    await db.exec(`set request.jwt.claim.sub='${owner}'; delete from tasks where id='${before.id}'`);
    assert.equal((await db.query(`select * from tasks where id='${before.id}'`)).rows.length, 0);
  } finally { await db.close(); }
});
